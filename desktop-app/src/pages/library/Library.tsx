/* ─── ItemCard ───────────────────────────────────────────────────── */

interface CardProps {
  item: LibraryItem;
  idx: number;
  menuId: string | null;
  setMenuId: (id: string | null) => void;
  toggleFav: (id: string) => void;
  deleteItem: (id: string) => void;
  listMode: boolean;
}

function ItemCard({ item, idx, menuId, setMenuId, toggleFav, deleteItem, listMode }: CardProps) {
  const menuOpen = menuId === item.id;

  function openMenu(e: React.MouseEvent) {
    e.stopPropagation();
    setMenuId(menuOpen ? null : item.id);
  }

  return (
    <motion.div
      className={`${styles.card} ${listMode ? styles.cardList : ""} ${menuOpen ? styles.cardMenuOpen : ""}`}
      initial={{ opacity: 0, y: 16, scale: 0.97 }}
      animate={{ opacity: 1, y: 0, scale: 1 }}
      transition={{ duration: 0.35, delay: idx * 0.04, ease: [0.16, 1, 0.3, 1] }}
      layout
    >
      {/* Thumbnail / icon area */}
      {!listMode && <Thumbnail item={item} />}

      {listMode && (
        <div className={styles.cardListIcon}>
          <TypeIcon item={item} small />
        </div>
      )}

      <div className={styles.cardBody}>
        <div className={styles.cardMeta}>
          <span className={styles.cardTag} style={{ color: tagColor(item) }}>{item.tag}</span>
          {item.lang && <span className={styles.cardLang} style={{ color: LANG_COLORS[item.lang] ?? "var(--text-secondary)" }}>{item.lang}</span>}
          {item.lines && <span className={styles.cardLines}>{item.lines} lines</span>}
        </div>
        <h3 className={styles.cardTitle}>{item.title}</h3>
        <p className={styles.cardSubtitle}>{item.subtitle}</p>
        <div className={styles.cardBottom}>
          <span className={styles.cardDate}><Clock size={11} /> {item.date}</span>
          <span className={styles.cardSize}>{item.size}</span>
        </div>
      </div>

      {/* Hover action strip */}
      <div className={styles.cardActions}>
        <button className={styles.cardAction} title="Open"><ExternalLink size={13} /></button>
        <button
          className={`${styles.cardAction} ${item.favorited ? styles.cardActionFav : ""}`}
          title={item.favorited ? "Unfavorite" : "Favorite"}
          onClick={e => { e.stopPropagation(); toggleFav(item.id); }}
        >
          <Heart size={13} fill={item.favorited ? "currentColor" : "none"} />
        </button>
        <button className={styles.cardAction} title="Download"><Download size={13} /></button>
        <button className={styles.cardAction} title="Share"><Share2 size={13} /></button>
        <div className={styles.cardMenuWrap}>
          <button className={styles.cardAction} title="More" onClick={openMenu}><MoreHorizontal size={13} /></button>
          <AnimatePresence>
            {menuOpen && (
              <motion.div
                className={styles.cardMenu}
                initial={{ opacity: 0, scale: 0.92, y: -6 }}
                animate={{ opacity: 1, scale: 1, y: 0 }}
                exit={{ opacity: 0, scale: 0.92, y: -6 }}
                transition={{ duration: 0.16, ease: [0.16, 1, 0.3, 1] }}
                onClick={e => e.stopPropagation()}
              >
                <button className={styles.cardMenuItem}><Lock size={12} /> Make private</button>
                <button className={styles.cardMenuItemDanger} onClick={() => deleteItem(item.id)}><Trash2 size={12} /> Delete</button>
              </motion.div>
            )}
          </AnimatePresence>
        </div>
      </div>

      {/* Favorited star badge */}
      {item.favorited && <span className={styles.favBadge}><Star size={10} fill="currentColor" /></span>}
    </motion.div>
  );
}

/* ─── Thumbnail ────────────────────────────────────────────────────── */

function Thumbnail({ item }: { item: LibraryItem }) {
  if (item.type === "image") {
    return (
      <div className={styles.thumbImage} style={{ background: item.gradient }}>
        <div className={styles.thumbImageOverlay}>
          <Image size={20} strokeWidth={1.5} />
        </div>
      </div>
    );
  }
  return (
    <div className={styles.thumbIcon}>
      <TypeIcon item={item} />
    </div>
  );
}

function TypeIcon({ item, small }: { item: LibraryItem; small?: boolean }) {
  const size = small ? 18 : 28;
  if (item.type === "code") return <FileCode size={size} style={{ color: LANG_COLORS[item.lang ?? ""] ?? "var(--accent-primary)" }} strokeWidth={1.6} />;
  const ExtIcon = EXT_ICONS[item.ext ?? ""] ?? FileText;
  if (item.type === "document") return <ExtIcon size={size} style={{ color: "var(--accent-primary)" }} strokeWidth={1.6} />;
  if (item.type === "file")     return <ExtIcon size={size} style={{ color: "var(--accent-warm)" }} strokeWidth={1.6} />;
  return <Folder size={size} style={{ color: "var(--accent-secondary)" }} strokeWidth={1.6} />;
}

/* ─── Empty state ───────────────────────────────────────────────────── */

function EmptyState({ tab, query }: { tab: Category; query: string }) {
  const msgs: Record<Category, [React.ElementType, string, string]> = {
    all:       [Folder,   "No items yet",              "Start creating with Jarvis AI."],
    images:    [Image,    "No generated images yet",   "Ask Jarvis Vision to create one."],
    code:      [Code2,    "No code files yet",          "Generate your first component."],
    documents: [FileText, "No documents yet",           "Let Jarvis write one for you."],
    files:     [Upload,   "No uploaded files",          "Drag and drop to upload."],
    favorites: [Star,     "No favorites yet",           "Heart items to save them here."],
  };
  const [Icon, title, sub] = msgs[tab];
  return (
    <motion.div
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0 }}
      transition={{ duration: 0.4 }}
      className={styles.empty}
    >
      <motion.div
        className={styles.emptyOrb}
        animate={{ y: [0, -8, 0] }}
        transition={{ duration: 4, repeat: Infinity, ease: "easeInOut" }}
      >
        <Icon size={28} strokeWidth={1.4} />
      </motion.div>
      <p className={styles.emptyTitle}>{query ? `No results for "${query}"` : title}</p>
      <p className={styles.emptySubtitle}>{query ? "Try a different search term." : sub}</p>
      {!query && (
        <motion.button whileHover={{ scale: 1.04 }} whileTap={{ scale: 0.97 }} className={styles.emptyBtn}>
          <Plus size={14} /> Create with Jarvis
        </motion.button>
      )}
    </motion.div>
  );
}

/* ─── Helpers ─────────────────────────────────────────────────────── */
function tagColor(item: LibraryItem) {
  if (item.type === "image")    return "var(--accent-secondary)";
  if (item.type === "code")     return "var(--accent-cyan)";
  if (item.type === "document") return "var(--accent-primary)";
  return "var(--accent-warm)";
}