function fmtMB(mb: number) {
  return mb >= 1024 ? `${(mb / 1024).toFixed(1)} GB` : `${mb} MB`;
}
const TOTAL_MB = STORAGE.reduce((s, x) => s + x.used, 0);
const TOTAL_CAP = 10240;

